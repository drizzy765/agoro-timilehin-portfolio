import { chromium } from "playwright";
const b = await chromium.launch({ args: ["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const ctx = await b.newContext({ viewport:{width:1280,height:800} });
const p = await ctx.newPage();
await p.goto("http://localhost:3210/", { waitUntil:"networkidle" });
await p.getByRole("button", { name: /Ask about Timi/i }).first().click();
const box = p.locator("textarea").first(); await box.waitFor();
await box.fill("What has Timi built with LLMs?");
await p.getByRole("button", { name: "Send" }).click();
const resp = await p.waitForResponse(r => r.url().includes("/api/chat"), { timeout: 30000 });
console.log("chat status", resp.status());
await p.waitForTimeout(12000);
const txt = await p.locator('[role="dialog"]').innerText();
console.log("DIALOG:", txt.slice(0,1500));
await p.screenshot({ path:"/workspace/portfolio/screens/chat-live.png" });
const a = await ctx.newPage();
await a.goto("http://localhost:3210/about", { waitUntil:"networkidle" });
await a.waitForTimeout(6000);
const card = a.locator("text=/Spotify|Discord|Now playing|Listening|offline/i").first();
console.log("lanyard text:", await a.evaluate(()=>[...document.querySelectorAll("p,span")].map(e=>e.textContent).filter(t=>/playing|spotify|listening|discord|offline/i.test(t||"")).slice(0,8)));
if (await card.count()) await card.scrollIntoViewIfNeeded();
await a.screenshot({ path:"/workspace/portfolio/screens/about-lanyard.png" });
await b.close();
